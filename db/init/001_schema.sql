-- Executado automaticamente SOMENTE na criação de um volume PostgreSQL vazio.
-- Para volumes existentes, aplicar manualmente após backup (ver README).
BEGIN;

CREATE TABLE IF NOT EXISTS administradores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    senha_hash TEXT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS estudantes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    matricula TEXT NOT NULL UNIQUE,
    curso TEXT,
    turma TEXT
);

CREATE TABLE IF NOT EXISTS responsaveis (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cpf TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS responsavel_estudante (
    responsavel_id INTEGER NOT NULL REFERENCES responsaveis(id) ON DELETE CASCADE,
    estudante_id INTEGER NOT NULL REFERENCES estudantes(id) ON DELETE CASCADE,
    PRIMARY KEY (responsavel_id, estudante_id)
);

CREATE TABLE IF NOT EXISTS solicitacoes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudante_id INTEGER NOT NULL REFERENCES estudantes(id),
    responsavel_id INTEGER REFERENCES responsaveis(id) ON DELETE SET NULL,
    tipo TEXT NOT NULL,
    justificativa TEXT NOT NULL,
    data_solicitada DATE,
    horario_solicitado TIME,
    status TEXT NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'APROVADA', 'REPROVADA')),
    administrador_id INTEGER REFERENCES administradores(id) ON DELETE SET NULL,
    observacao_coordenacao TEXT,
    analisado_em TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_solicitacoes_status_criado
    ON solicitacoes (status, criado_em);
CREATE INDEX IF NOT EXISTS idx_responsavel_estudante_estudante
    ON responsavel_estudante (estudante_id);

COMMIT;
